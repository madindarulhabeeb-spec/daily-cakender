  /**
   * Get Kasaragod Prayer Times from official timetable lookup
   * Falls back to astronomical calculation if date out of range
   */
  getKasaragodPrayerTimes(date) {
    const month = date.getMonth() + 1; // 1-12
    const day = date.getDate();        // 1-31

    const monthData = this.KASARAGOD_TIMETABLE[month];
    if (monthData && monthData[day - 1]) {
      const [fajr, sunrise, dhuhr, asr, maghrib, isha] = monthData[day - 1];
      return {
        subah: fajr,
        thulu: sunrise,
        dhuhr: dhuhr,
        asr: asr,
        maghrib: maghrib,
        isha: isha
      };
    }

    // Fallback: astronomical approximation
    return this._calcPrayerFallback(date);
  },

  /**
   * Fallback astronomical prayer time calculation for edge cases
   */
  _calcPrayerFallback(date) {
    const lat = 12.5102;
    const lon = 74.9852;
    const timezone = 5.5;

    const startOfYear = new Date(date.getFullYear(), 0, 0);
    const dayOfYear = Math.floor((date - startOfYear) / (1000 * 60 * 60 * 24));

    const rad = d => d * (Math.PI / 180);
    const deg = r => r * (180 / Math.PI);

    const b = (2 * Math.PI * (dayOfYear - 81)) / 365;
    const eot = 9.87 * Math.sin(2 * b) - 7.53 * Math.cos(b) - 1.5 * Math.sin(b);
    const declination = deg(Math.asin(Math.sin(rad(23.45)) * Math.sin(b)));
    const solarNoon = 12 - (lon / 15) + timezone - (eot / 60);

    const hourAngle = (angle) => {
      const cosH = (Math.sin(rad(angle)) - Math.sin(rad(lat)) * Math.sin(rad(declination))) /
                   (Math.cos(rad(lat)) * Math.cos(rad(declination)));
      if (cosH > 1 || cosH < -1) return null;
      return deg(Math.acos(cosH)) / 15;
    };

    const fajrHA = hourAngle(-18.0);
    const sunriseHA = hourAngle(-0.833);
    const phi = Math.abs(lat - declination);
    const asrAngle = deg(Math.atan(1 / (1 + Math.tan(rad(phi)))));
    const asrHA = hourAngle(asrAngle);

    const fmt = (decimalHour) => {
      let totalMinutes = Math.round(decimalHour * 60);
      let h = Math.floor(totalMinutes / 60) % 12;
      if (h === 0) h = 12;
      let m = totalMinutes % 60;
      return `${h < 10 ? '0' + h : h}:${m < 10 ? '0' + m : m}`;
    };

    return {
      subah:   fmt(solarNoon - (fajrHA || 1.7)),
      thulu:   fmt(solarNoon - (sunriseHA || 1.5)),
      dhuhr:   fmt(solarNoon + 2/60),
      asr:     fmt(solarNoon + (asrHA || 1.6)),
      maghrib: fmt(solarNoon + (sunriseHA || 1.5) + 2/60),
      isha:    fmt(solarNoon + (fajrHA || 1.7) + 1/60)
    };
  }
